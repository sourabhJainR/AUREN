"""Fail-closed live provider and license readiness for engineering releases.

The host supplies live probes, trusted evidence verifiers, and the exact intended
use. This module never discovers credentials, infers license rights, or treats a
static provider manifest as live validation.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
import hashlib
import json
import re
from typing import Any, Callable, Mapping
from urllib.parse import urlparse


class ProviderReadinessError(ValueError):
    """Provider readiness input or evidence is malformed."""


def _canonical(value: Mapping[str, Any]) -> bytes:
    return json.dumps(
        dict(value), sort_keys=True, separators=(",", ":"),
        ensure_ascii=False, allow_nan=False,
    ).encode("utf-8")


def _digest(value: Mapping[str, Any], *, omit: tuple[str, ...] = ()) -> str:
    return hashlib.sha256(_canonical({k: v for k, v in value.items() if k not in omit})).hexdigest()


def _sha256(value: Any, field: str) -> str:
    if not isinstance(value, str) or re.fullmatch(r"[0-9a-f]{64}", value) is None:
        raise ProviderReadinessError(f"{field} must be a lowercase SHA-256 digest")
    return value


def _timestamp(value: Any, field: str) -> datetime:
    if not isinstance(value, str) or not value.strip():
        raise ProviderReadinessError(f"{field} must be an ISO-8601 timestamp")
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ProviderReadinessError(f"{field} must be an ISO-8601 timestamp") from exc
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ProviderReadinessError(f"{field} must include a timezone")
    return parsed.astimezone(timezone.utc)


def _required_text(value: Any, field: str, limit: int = 256) -> str:
    if not isinstance(value, str) or not value.strip() or len(value.strip()) > limit:
        raise ProviderReadinessError(f"{field} must be non-empty bounded text")
    return value.strip()


@dataclass(frozen=True, slots=True)
class ProviderReadinessReport:
    provider_id: str
    capability: str
    intended_use: str
    task_id: str
    run_id: str
    artifact_digest: str
    plan_digest: str
    status: str
    blocking_reasons: tuple[str, ...]
    live_probe_digest: str | None
    license_evidence_digest: str | None
    evidence_digest: str

    @property
    def ready(self) -> bool:
        return self.status == "passed"

    def as_dict(self) -> dict[str, Any]:
        return {
            "schema_version": "auren-provider-readiness-v1",
            "provider_id": self.provider_id,
            "capability": self.capability,
            "intended_use": self.intended_use,
            "task_id": self.task_id,
            "run_id": self.run_id,
            "artifact_digest": self.artifact_digest,
            "plan_digest": self.plan_digest,
            "status": self.status,
            "ready": self.ready,
            "blocking_reasons": list(self.blocking_reasons),
            "live_probe_digest": self.live_probe_digest,
            "license_evidence_digest": self.license_evidence_digest,
            "evidence_digest": self.evidence_digest,
        }


_PROBE_FIELDS = {
    "schema_version", "provider_id", "capability", "challenge_id", "status",
    "observed_at", "latency_ms", "provider_version", "adapter_id", "evidence_digest",
}
_LICENSE_FIELDS = {
    "schema_version", "provider_id", "intended_use", "terms_uri", "terms_digest",
    "reviewed_at", "expires_at", "reviewer_principal_id", "approved",
    "permitted_uses", "redistribution_allowed", "commercial_use_allowed",
    "storage_allowed", "evidence_digest",
}


def evaluate_provider_readiness(
    *,
    provider_id: str,
    capability: str,
    intended_use: str,
    task_id: str,
    run_id: str,
    artifact_digest: str,
    plan_digest: str,
    challenge_id: str,
    live_probe: Mapping[str, Any] | None,
    license_evidence: Mapping[str, Any] | None,
    verify_live_probe: Callable[[Mapping[str, Any]], bool] | None,
    verify_license_evidence: Callable[[Mapping[str, Any]], bool] | None,
    requires_redistribution: bool = False,
    requires_commercial_use: bool = False,
    requires_storage: bool = False,
    now: datetime | None = None,
    max_probe_age_seconds: int = 300,
    max_license_age_seconds: int = 90 * 24 * 60 * 60,
) -> ProviderReadinessReport:
    """Validate fresh host-authenticated provider and license evidence.

    challenge_id must be freshly generated by the trusted host for this attempt.
    The two verifier callbacks must validate host/provider signatures or equivalent
    trusted receipts; returning True for caller-authored fixtures is not production
    evidence. No credential or raw provider response is copied into the report.
    """
    provider_id = _required_text(provider_id, "provider_id")
    capability = _required_text(capability, "capability")
    intended_use = _required_text(intended_use, "intended_use")
    task_id = _required_text(task_id, "task_id")
    run_id = _required_text(run_id, "run_id")
    challenge_id = _required_text(challenge_id, "challenge_id")
    artifact_digest = _sha256(artifact_digest, "artifact_digest")
    plan_digest = _sha256(plan_digest, "plan_digest")
    for field, value in (
        ("max_probe_age_seconds", max_probe_age_seconds),
        ("max_license_age_seconds", max_license_age_seconds),
    ):
        if type(value) is not int or value < 1:
            raise ProviderReadinessError(f"{field} must be a positive integer")
    current = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
    reasons: list[str] = []
    probe_digest: str | None = None
    license_digest: str | None = None
    failed = False

    if live_probe is None:
        reasons.append("live_provider_probe_missing")
    else:
        try:
            if not isinstance(live_probe, Mapping) or set(live_probe) != _PROBE_FIELDS:
                raise ProviderReadinessError("live provider receipt fields are invalid")
            probe = dict(live_probe)
            if probe["schema_version"] != "auren-provider-live-probe-v1":
                raise ProviderReadinessError("unsupported live provider receipt schema")
            if probe["provider_id"] != provider_id or probe["capability"] != capability:
                raise ProviderReadinessError("live provider receipt identity or capability mismatch")
            if probe["challenge_id"] != challenge_id:
                raise ProviderReadinessError("live provider receipt challenge mismatch")
            if probe["status"] != "passed":
                reasons.append("live_provider_probe_not_passed")
            if type(probe["latency_ms"]) is not int or probe["latency_ms"] < 0:
                raise ProviderReadinessError("live provider latency is invalid")
            _required_text(probe["provider_version"], "provider_version")
            _required_text(probe["adapter_id"], "adapter_id")
            observed_at = _timestamp(probe["observed_at"], "observed_at")
            if observed_at > current + timedelta(seconds=30):
                reasons.append("live_provider_probe_from_future")
            elif (current - observed_at).total_seconds() > max_probe_age_seconds:
                reasons.append("live_provider_probe_stale")
            probe_digest = _sha256(probe["evidence_digest"], "live probe evidence_digest")
            if probe_digest != _digest(probe, omit=("evidence_digest",)):
                raise ProviderReadinessError("live provider receipt digest mismatch")
            if not callable(verify_live_probe) or verify_live_probe(probe) is not True:
                raise ProviderReadinessError("live provider receipt is not host-authenticated")
        except Exception as exc:
            failed = True
            reasons.append(f"live_provider_evidence_invalid:{type(exc).__name__}")

    if license_evidence is None:
        reasons.append("provider_license_evidence_missing")
    else:
        try:
            if not isinstance(license_evidence, Mapping) or set(license_evidence) != _LICENSE_FIELDS:
                raise ProviderReadinessError("provider license evidence fields are invalid")
            license_record = dict(license_evidence)
            if license_record["schema_version"] != "auren-provider-license-v1":
                raise ProviderReadinessError("unsupported provider license evidence schema")
            if license_record["provider_id"] != provider_id:
                raise ProviderReadinessError("provider license identity mismatch")
            if license_record["intended_use"] != intended_use:
                raise ProviderReadinessError("provider license intended-use mismatch")
            terms_uri = _required_text(license_record["terms_uri"], "terms_uri", 2048)
            parsed_uri = urlparse(terms_uri)
            if parsed_uri.scheme != "https" or not parsed_uri.netloc:
                raise ProviderReadinessError("terms_uri must be an HTTPS source")
            _sha256(license_record["terms_digest"], "terms_digest")
            reviewed_at = _timestamp(license_record["reviewed_at"], "reviewed_at")
            expires_at = _timestamp(license_record["expires_at"], "expires_at")
            if reviewed_at > current + timedelta(seconds=30):
                reasons.append("provider_license_review_from_future")
            elif (current - reviewed_at).total_seconds() > max_license_age_seconds:
                reasons.append("provider_license_review_stale")
            if expires_at <= current:
                reasons.append("provider_license_evidence_expired")
            _required_text(license_record["reviewer_principal_id"], "reviewer_principal_id")
            if license_record["approved"] is not True:
                reasons.append("provider_license_not_approved")
            uses = license_record["permitted_uses"]
            if not isinstance(uses, list) or any(not isinstance(item, str) for item in uses):
                raise ProviderReadinessError("permitted_uses must be a list of strings")
            if intended_use not in uses:
                reasons.append("provider_license_use_not_permitted")
            for key in ("redistribution_allowed", "commercial_use_allowed", "storage_allowed"):
                if type(license_record[key]) is not bool:
                    raise ProviderReadinessError(f"{key} must be boolean")
            if requires_redistribution and not license_record["redistribution_allowed"]:
                reasons.append("provider_license_redistribution_not_permitted")
            if requires_commercial_use and not license_record["commercial_use_allowed"]:
                reasons.append("provider_license_commercial_use_not_permitted")
            if requires_storage and not license_record["storage_allowed"]:
                reasons.append("provider_license_storage_not_permitted")
            license_digest = _sha256(license_record["evidence_digest"], "license evidence_digest")
            if license_digest != _digest(license_record, omit=("evidence_digest",)):
                raise ProviderReadinessError("provider license evidence digest mismatch")
            if not callable(verify_license_evidence) or verify_license_evidence(license_record) is not True:
                raise ProviderReadinessError("provider license evidence is not host-authenticated")
        except Exception as exc:
            failed = True
            reasons.append(f"provider_license_evidence_invalid:{type(exc).__name__}")

    status = "failed" if failed else ("blocked" if reasons else "passed")
    payload = {
        "schema_version": "auren-provider-readiness-v1",
        "provider_id": provider_id,
        "capability": capability,
        "intended_use": intended_use,
        "task_id": task_id,
        "run_id": run_id,
        "artifact_digest": artifact_digest,
        "plan_digest": plan_digest,
        "status": status,
        "blocking_reasons": reasons,
        "live_probe_digest": probe_digest,
        "license_evidence_digest": license_digest,
    }
    return ProviderReadinessReport(
        provider_id, capability, intended_use, task_id, run_id, artifact_digest,
        plan_digest, status, tuple(reasons), probe_digest, license_digest,
        hashlib.sha256(_canonical(payload)).hexdigest(),
    )


__all__ = [
    "ProviderReadinessError", "ProviderReadinessReport",
    "evaluate_provider_readiness",
]
